const KANJI = '[\\u4e00-\\u9fff々]';
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const KEYS = Object.keys(RUBY).sort((a, b) => b.length - a.length);
// 漢字の前後がほかの漢字につながっていないところだけに当てはめる（「心臓」の「臓」だけに当てないように）
const PATTERN = new RegExp(`(?<!${KANJI})(?:${KEYS.map(escapeRe).join('|')})`, 'g');

// 文字列を、ふつうの文字と [漢字, よみ] の並びに分ける。
// skipQuoted: true のときは「」の中にはつけない（国語の「読み方」の問題で答えが分からないように）
export function rubySegments(text, { skipQuoted = false } = {}) {
  const out = [];
  const parts = skipQuoted ? String(text).split(/(「[^」]*」)/) : [String(text)];
  for (const part of parts) {
    if (skipQuoted && part.startsWith('「')) { out.push(part); continue; }
    let last = 0;
    for (const m of part.matchAll(PATTERN)) {
      if (m.index < last) continue;
      const key = m[0];
      const kanji = key.match(new RegExp(`^${KANJI}+`))[0];
      const end = m.index + kanji.length;
      // 漢字のすぐ後ろにまだ漢字が続くとき（表にない長い言葉の一部）は、つけない
      if (key === kanji && new RegExp(KANJI).test(part[end] ?? '')) continue;
      if (m.index > last) out.push(part.slice(last, m.index));
      out.push([kanji, RUBY[key]]);
      last = end;
    }
    if (last < part.length) out.push(part.slice(last));
  }
  return out;
}

// 文字列を、ふりがなつきの DOM（DocumentFragment）にする
export function rubyFragment(text, opts) {
  const frag = document.createDocumentFragment();
  for (const seg of rubySegments(text, opts)) {
    if (typeof seg === 'string') { frag.append(seg); continue; }
    const ruby = document.createElement('ruby');
    ruby.append(seg[0]);
    const rt = document.createElement('rt');
    rt.textContent = seg[1];
    ruby.append(rt);
    frag.append(ruby);
  }
  return frag;
}
